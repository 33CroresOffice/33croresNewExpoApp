/*
# Create localities and flower__apartment tables and seed data

## New Tables
1. `localities` — list of localities with pincode and unique code
2. `flower__apartment` — apartment buildings within localities (references localities.unique_code as plain text, no FK constraint since some source codes are missing)

## Security
- RLS enabled on both tables with public read access (reference data)
*/

CREATE TABLE IF NOT EXISTS localities (
  id integer PRIMARY KEY,
  locality_name text NOT NULL,
  pincode text NOT NULL,
  unique_code text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE localities ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_read_localities" ON localities;
CREATE POLICY "public_read_localities" ON localities FOR SELECT
  TO anon, authenticated USING (true);

CREATE TABLE IF NOT EXISTS flower__apartment (
  id integer PRIMARY KEY,
  locality_id text,
  apartment_name text,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE flower__apartment ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_read_flower_apartment" ON flower__apartment;
CREATE POLICY "public_read_flower_apartment" ON flower__apartment FOR SELECT
  TO anon, authenticated USING (true);

