/*
  # Migrate Subscriptions Data

  ## Summary
  Migrates subscription records from the CSV export into the `subscriptions` table,
  and creates a subscription_id_mapping table for referencing CSV logical IDs later.

  ## Changes
  1. New Tables
    - `subscription_id_mapping`: Maps logical SUB-xxx IDs to internal subscription UUIDs

  2. Subscription Status Mapping
    - "active" → "active"
    - "paused" → "paused"
    - "cancelled" → "cancelled"
    - "expired" → "expired"
    - "renewed" → "renewed"
    - "dead" → "cancelled" (treated as cancelled/terminated)
    - "pending" → "active" (pending = not yet started, treated as active)

  3. Plan ID Mapping
    - CSV uses logical plan codes (FLOW1977643, PRODUCT9336986 etc.)
    - All plans mapped to existing subscription_plans UUIDs based on plan type
    - FLOW* plans → monthly plan (54946a45-cf58-4b32-8600-159601d62568)
    - PRODUCT* plans → premium pack (0dd17a97-aeae-4dca-bd10-2cbeee353494)

  ## Notes
  - Only inserts where logical user_id maps to a known profile UUID
  - Skips duplicate subscriptions (same logical_id already in mapping)
  - subscription_id_mapping enables pause history migration to reference correct UUIDs
*/

